-- P2-5 phase 2, batch 2 of Category B (2026-09-03 launch audit, CEO-
-- approved "full consolidation, small batches with tests" — follow-up to
-- batch 1's 20260903180000, same methodology).
--
-- Scope: all remaining (table, command, role) groups with exactly 2
-- PERMISSIVE policies, same role, that batch 1 didn't cover — 19 tables,
-- 23 groups. Deliberately excludes the 3-6-policy groups (quiz_responses
-- SELECT, foxy_chat_messages SELECT, students, etc.) and the `students`
-- table specifically (its own dedicated recursion-guard test section
-- treats it as an apex/high-sensitivity case; merging it deserves standalone
-- handling, not a routine batch) — tracked as later batches.
--
-- METHOD (unchanged from batch 1): every USING/WITH CHECK clause below was
-- generated by a script from the EXACT live pg_policies qual/with_check
-- text pulled immediately before writing this file — never hand-retyped.
-- INSERT-only groups merge WITH CHECK only (INSERT policies have no
-- USING); UPDATE groups merge both USING and WITH CHECK (each
-- independently ORed across the source policies, preserving the exact
-- pre-existing pre-row/post-row semantics of each).
--
-- Also unchanged: only merged groups sharing the identical `roles` value.
-- xp_transactions and teacher_parent_messages each ALSO carry an
-- additional policy with a DIFFERENT roles value on the very same command
-- (xp_txn_parent_select is `{public}` where the two merged here are
-- `{authenticated}`) — deliberately left untouched; a `{public}` policy
-- applies to every role including authenticated, so folding it into an
-- `authenticated`-only merged policy would either silently drop anon/other
-- access (if merged as `TO authenticated`) or widen the other two policies'
-- intended scope (if merged as `TO public`) — a real semantic question, not
-- a hygiene merge, deferred rather than guessed at.
--
-- storage.objects (INSERT): note this is Supabase's own Storage system
-- table, not an application table under `public`. The two merged policies
-- are self-contained per bucket (each ANDs its own `bucket_id = '...'`
-- check), so ORing them together changes nothing about which upload
-- succeeds for which bucket — merging is safe. Storage RLS is ordinary
-- pg_policies underneath; the Supabase Storage dashboard reads/writes the
-- same catalog, so a policy rename is transparent to it.
--
-- Recursion-guard ledger: see the companion update to
-- apps/host/src/__tests__/rls-no-cross-table-recursion.test.ts in this same
-- PR for the GRANDFATHERED_INLINE_POLICIES swap this batch requires (every
-- one of these tables' "_own_*"-style policies inlines the same
-- `student_id IN (SELECT s.id FROM students s WHERE s.auth_user_id =
-- auth.uid())` cross-table pattern as batch 1, so every merge here is
-- expected to trip the same "NEW/RENAMED inline policy" detection for a
-- pre-existing, not new, risk).

-- -- public.bloom_progression (INSERT, authenticated): merge 2 policies --
DROP POLICY IF EXISTS "Students can insert own bloom_progression" ON public.bloom_progression;
DROP POLICY IF EXISTS "bloom_progression_own_insert" ON public.bloom_progression;
CREATE POLICY "bloom_progression_insert_merged" ON public.bloom_progression
  FOR INSERT TO authenticated
  WITH CHECK (
  ((student_id = get_my_student_id()))
  OR (((student_id = ( SELECT auth.uid() AS uid)) OR (student_id IN ( SELECT s.id
   FROM students s
  WHERE (s.auth_user_id = ( SELECT auth.uid() AS uid))))))
  );

