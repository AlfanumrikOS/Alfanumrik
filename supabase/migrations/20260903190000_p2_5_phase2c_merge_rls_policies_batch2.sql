-- -- public.teacher_parent_messages (INSERT, public): merge 2 policies --
DROP POLICY IF EXISTS "tp_messages_guardian_insert" ON public.teacher_parent_messages;
DROP POLICY IF EXISTS "tp_messages_teacher_insert" ON public.teacher_parent_messages;
CREATE POLICY "teacher_parent_messages_insert_merged" ON public.teacher_parent_messages
  FOR INSERT TO public
  WITH CHECK (
  (((sender_role = 'guardian'::text) AND (sender_auth_user_id = ( SELECT auth.uid() AS uid)) AND (thread_id IN ( SELECT th.id
   FROM (teacher_parent_threads th
     JOIN guardians g ON ((g.id = th.guardian_id)))
  WHERE (g.auth_user_id = ( SELECT auth.uid() AS uid))))))
  OR (((sender_role = 'teacher'::text) AND (sender_auth_user_id = ( SELECT auth.uid() AS uid)) AND (thread_id IN ( SELECT th.id
   FROM (teacher_parent_threads th
     JOIN teachers t ON ((t.id = th.teacher_id)))
  WHERE (t.auth_user_id = ( SELECT auth.uid() AS uid))))))
  );

